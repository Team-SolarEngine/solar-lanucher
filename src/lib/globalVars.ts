export function sanitizeTerminal(str: string) {
    return str
        .replaceAll("!", "-")
        .replaceAll("@", "-")
        .replaceAll("#", "-")
        .replaceAll("$", "-")
        .replaceAll("%", "-")
        .replaceAll("^", "-")
        .replaceAll("&", "-")
        .replaceAll("*", "-")
        .replaceAll("(", "-")
        .replaceAll(")", "-")
        .replaceAll("\\", "-")
        .replaceAll("]", "-")
        .replaceAll("}", "-")
        .replaceAll("[", "-")
        .replaceAll("{", "-")
        .replaceAll("'", "-")
        .replaceAll("\"", "-")
        .replaceAll(";", "-")
        .replaceAll(":", "-")
        .replaceAll("?", "-")
        .replaceAll(".", "-")
        .replaceAll(">", "-")
        .replaceAll("<", "-")
        .replaceAll(",", "-")
}